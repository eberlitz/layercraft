//! `cargo xtask licences [--check]`: audits transitive dependencies against permissive licenses
//! and writes/verifies `THIRD-PARTY-LICENSES.txt`.

use std::collections::{BTreeMap, BTreeSet, VecDeque};
use std::path::Path;

use cargo_metadata::{DependencyKind, MetadataCommand};

pub const FILE: &str = "THIRD-PARTY-LICENSES.txt";

const ALLOWED_SPDX: &[&str] = &[
    "MIT",
    "Apache-2.0",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "ISC",
    "Zlib",
    "BSL-1.0",
    "Unicode-3.0",
    "Unicode-DFS-2016",
    "CC0-1.0",
    "Unlicense",
    "0BSD",
    "CDLA-Permissive-2.0",
    "OFL-1.1",
    "Ubuntu-font-1.0",
];

const SHIPPED_ROOTS: &[&str] = &[
    "layercraft",
    "layercraft-cli",
    "layercraft-web",
    "layercraft-geom",
    "layercraft-clip",
    "layercraft-mesh",
    "layercraft-config",
    "layercraft-slice",
    "layercraft-gcode",
    "layercraft-io",
    "layercraft-engine",
    "layercraft-viewport",
    "layercraft-viewport-gpu",
    "layercraft-ui-egui",
    "layercraft-mcp",
];

pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let metadata = MetadataCommand::new()
        .manifest_path(root.join("Cargo.toml"))
        .exec()
        .map_err(|e| format!("cargo metadata failed: {e}"))?;

    let workspace_ids: BTreeSet<_> = metadata.workspace_members.iter().cloned().collect();
    let mut id_to_pkg = BTreeMap::new();
    for pkg in &metadata.packages {
        id_to_pkg.insert(pkg.id.clone(), pkg);
    }

    let Some(resolve) = metadata.resolve.as_ref() else {
        return Err("cargo metadata missing resolve graph".to_owned());
    };
    let mut adj: BTreeMap<cargo_metadata::PackageId, Vec<cargo_metadata::PackageId>> =
        BTreeMap::new();
    for node in &resolve.nodes {
        let list = adj.entry(node.id.clone()).or_default();
        for dep in &node.deps {
            let is_non_dev = dep.dep_kinds.is_empty()
                || dep
                    .dep_kinds
                    .iter()
                    .any(|k| k.kind == DependencyKind::Normal || k.kind == DependencyKind::Build);
            if is_non_dev {
                list.push(dep.pkg.clone());
            }
        }
    }

    let mut queue = VecDeque::new();
    let mut visited = BTreeSet::new();
    for pkg in &metadata.packages {
        if workspace_ids.contains(&pkg.id)
            && SHIPPED_ROOTS.contains(&pkg.name.as_str())
            && visited.insert(pkg.id.clone())
        {
            queue.push_back(pkg.id.clone());
        }
    }
    while let Some(id) = queue.pop_front() {
        if let Some(nexts) = adj.get(&id) {
            for nid in nexts {
                if visited.insert(nid.clone()) {
                    queue.push_back(nid.clone());
                }
            }
        }
    }

    let mut entries: Vec<(String, String, String)> = Vec::new();
    let mut violations: Vec<String> = Vec::new();
    for id in &visited {
        if workspace_ids.contains(id) {
            continue;
        }
        let Some(pkg) = id_to_pkg.get(id) else {
            continue;
        };
        let lic = pkg.license.clone().unwrap_or_else(|| "UNKNOWN".to_owned());
        if !allows_spdx(&lic) {
            violations.push(format!("  {} {} ({})", pkg.name, pkg.version, lic));
        }
        entries.push((pkg.name.to_string(), pkg.version.to_string(), lic));
    }

    if !violations.is_empty() {
        return Err(format!(
            "copyleft or disallowed dependency license detected (AGENTS.md clean-room policy):\n{}",
            violations.join("\n")
        ));
    }

    entries.sort();
    let mut text = String::from(
        "# Third-Party Licenses for LayerCraft Shipped Crates\n\
         # Generated by `cargo xtask licences`. Do not edit manually.\n\n",
    );
    for (name, ver, lic) in &entries {
        text.push_str(&format!("{name} {ver}: {lic}\n"));
    }

    let path = root.join(FILE);
    if check {
        let existing = std::fs::read_to_string(&path).unwrap_or_default();
        if existing.replace("\r\n", "\n") != text {
            return Err(format!(
                "{FILE} is out of date — run `cargo xtask licences` to regenerate it"
            ));
        }
        println!(
            "licences: OK ({} permissive crates audited, {FILE} up to date)",
            entries.len()
        );
        return Ok(());
    }

    std::fs::write(&path, &text).map_err(|e| format!("{}: {e}", path.display()))?;
    println!(
        "licences: wrote {FILE} ({} permissive third-party crates)",
        entries.len()
    );
    Ok(())
}

/// Evaluate an SPDX license expression; succeeds only if at least one `OR` branch
/// (and all `AND` requirements in that branch) consists solely of allowed permissive SPDX IDs.
pub fn allows_spdx(expr: &str) -> bool {
    let tokens = tokenize_spdx(expr);
    if tokens.is_empty() {
        return false;
    }
    let mut pos = 0usize;
    match parse_or(&tokens, &mut pos) {
        Some(ok) => ok && pos == tokens.len(),
        None => false,
    }
}

#[derive(Debug, PartialEq, Eq)]
enum Tok {
    LParen,
    RParen,
    And,
    Or,
    With,
    Ident(String),
}

fn tokenize_spdx(expr: &str) -> Vec<Tok> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let flush = |cur: &mut String, out: &mut Vec<Tok>| {
        if cur.is_empty() {
            return;
        }
        let s = std::mem::take(cur);
        match s.as_str() {
            "AND" => out.push(Tok::And),
            "OR" => out.push(Tok::Or),
            "WITH" => out.push(Tok::With),
            "/" => out.push(Tok::Or),
            _ => out.push(Tok::Ident(s)),
        }
    };
    for ch in expr.chars() {
        if ch.is_whitespace() {
            flush(&mut cur, &mut out);
        } else if ch == '(' {
            flush(&mut cur, &mut out);
            out.push(Tok::LParen);
        } else if ch == ')' {
            flush(&mut cur, &mut out);
            out.push(Tok::RParen);
        } else if ch == '/' {
            flush(&mut cur, &mut out);
            out.push(Tok::Or);
        } else {
            cur.push(ch);
        }
    }
    flush(&mut cur, &mut out);
    out
}

fn parse_or(tokens: &[Tok], pos: &mut usize) -> Option<bool> {
    let mut val = parse_and(tokens, pos)?;
    while matches!(tokens.get(*pos), Some(Tok::Or)) {
        *pos += 1;
        let rhs = parse_and(tokens, pos)?;
        val = val || rhs;
    }
    Some(val)
}

fn parse_and(tokens: &[Tok], pos: &mut usize) -> Option<bool> {
    let mut val = parse_atom(tokens, pos)?;
    while matches!(tokens.get(*pos), Some(Tok::And)) {
        *pos += 1;
        let rhs = parse_atom(tokens, pos)?;
        val = val && rhs;
    }
    Some(val)
}

fn parse_atom(tokens: &[Tok], pos: &mut usize) -> Option<bool> {
    match tokens.get(*pos)? {
        Tok::LParen => {
            *pos += 1;
            let inner = parse_or(tokens, pos)?;
            if !matches!(tokens.get(*pos), Some(Tok::RParen)) {
                return None;
            }
            *pos += 1;
            Some(inner)
        }
        Tok::Ident(id) => {
            let mut ok = ALLOWED_SPDX.contains(&id.as_str());
            *pos += 1;
            if matches!(tokens.get(*pos), Some(Tok::With)) {
                *pos += 1;
                if let Some(Tok::Ident(_exc)) = tokens.get(*pos) {
                    *pos += 1;
                } else {
                    return None;
                }
                // Treat WITH LLVM-exception on Apache-2.0 as permissive.
                ok = ok && id == "Apache-2.0";
            }
            Some(ok)
        }
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn spdx_parser_blocks_copyleft_and_allows_permissive_or_branches() {
        assert!(allows_spdx("MIT OR Apache-2.0"));
        assert!(allows_spdx("(MIT OR Apache-2.0) AND Unicode-3.0"));
        assert!(allows_spdx("GPL-3.0 OR MIT"));
        assert!(!allows_spdx("GPL-3.0-only"));
        assert!(!allows_spdx("AGPL-3.0-or-later"));
        assert!(!allows_spdx("MIT AND LGPL-2.1"));
        assert!(!allows_spdx("MPL-2.0"));
    }
}
